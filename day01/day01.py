# ① print()：让电脑说话。引号里的内容叫"字符串"
print("Hello, World!")
print("我是你的第一个 Python 程序")

# ② 变量：给数据起个名字，方便以后使用
name = "小明"        # 文字（字符串）
age = 18            # 整数
height = 1.75       # 小数（浮点数）

# ③ f-string：把变量嵌进文字里，注意前面有个 f
print(f"{name} 今年 {age} 岁，身高 {height} 米")

# ④ 变量是可以改变的，这就是"变"量的意思
age = age + 1
print("过完生日后：", age)

# ⑤ input()：等待用户输入一行内容（返回的永远是字符串）
your_name = input("请输入你的名字：")
print(f"你好, {your_name}! 欢迎来到 Python 的世界 🐍")
